"""Draws the Detent app icon and writes it as the Android adaptive-icon layers and the site favicon.

The icon is the 'soft · radial · double' dial in the koi-watercolor colours: dots swell toward the
notch, a fainter inner arc marks each app, and the notch is a teal dot on a dark halo.

Run it from the repository folder:

    python3 tools/icon/make.py
"""

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DRAWABLE = ROOT / "app/src/main/res/drawable"
FAVICON = ROOT / "docs/icon.svg"

# The koi-watercolor theme. The notch takes a lighter teal than the theme accent,
# so it stays clear on the dark teal at launcher sizes.
FG = "#D8E0DC"
NOTCH = "#8CCBD2"
HALO = "#0F2A2F"
GLOW_INNER = "#1A3F45"
GLOW_OUTER = "#0C1C1F"
# The glow sits up and to the right of the centre, toward the names side of the dial.
GLOW_CENTER = (0.62, 0.42)
GLOW_RADIUS = 0.75

# The adaptive-icon grid is 108 units. Launchers show the middle 72, and every mask keeps
# the circle of radius 33 around the centre, so the dial sits inside that circle.
GRID = 108
CENTER = GRID / 2
DIAL_CX, DIAL_R = 90, 46          # the dial's centre is to the right, so its rim curves in from the right edge
HALF_SPAN, STEPS, PER_APP = 46, 16, 4
INNER_ARC = 11                    # distance from the rim to the fainter inner dots
NOTCH_DEG = 180                   # the notch sits on the left-most point of the rim, like the selected row


def fmt(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def on_rim(deg, inset=0.0):
    rad = math.radians(deg)
    r = DIAL_R - inset
    return DIAL_CX + r * math.cos(rad), CENTER + r * math.sin(rad)


def dial_layers():
    """The icon as an ordered list of (colour, alpha, circles), each circle (x, y, r).
    Later layers paint over earlier ones, so the halo can clear the dots around the notch."""
    dots = {}
    for i in range(-STEPS, STEPS + 1):
        if i == 0:
            continue
        rows_from_notch = abs(i) / PER_APP
        swell = max(0.0, 1 - rows_from_notch / 3.6)
        fade = (1 - abs(i) / STEPS) ** 0.8
        major = i % PER_APP == 0
        deg = NOTCH_DEG + i * HALF_SPAN / STEPS
        x, y = on_rim(deg)
        size = (2.6 + 5.2 * swell) if major else (1.6 + 2.4 * swell)
        alpha = round((0.35 + 0.6 * swell) * fade + 0.05, 2)
        dots.setdefault(alpha, []).append((x, y, size / 2))
        if major:
            ix, iy = on_rim(deg, INNER_ARC)
            inner_alpha = round((0.25 + 0.45 * swell) * fade, 2)
            dots.setdefault(inner_alpha, []).append((ix, iy, (2.2 + 2.6 * swell) / 2))

    nx, ny = on_rim(NOTCH_DEG)
    # The outermost inner dots fade to nothing, so they are left out.
    layers = [(FG, alpha, circles) for alpha, circles in sorted(dots.items()) if alpha > 0]
    layers.append((HALO, 1.0, [(nx, ny, 7.6)]))
    layers.append((NOTCH, 1.0, [(nx, ny, 5.2)]))
    layers.append((FG, 0.8, [(nx + INNER_ARC, ny, 2.5)]))
    return layers


def circle_path(circles):
    return "".join(
        f"M{fmt(x - r)},{fmt(y)}a{fmt(r)},{fmt(r)} 0 1,0 {fmt(2 * r)},0a{fmt(r)},{fmt(r)} 0 1,0 {fmt(-2 * r)},0Z"
        for x, y, r in circles
    )


HEADER = "<!-- Generated by tools/icon/make.py. Edit that script, not this file. -->"
VECTOR_OPEN = (
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra}\n'
    f'    android:width="{GRID}dp" android:height="{GRID}dp"\n'
    f'    android:viewportWidth="{GRID}" android:viewportHeight="{GRID}">\n'
)


def vector(body, extra=""):
    return f'<?xml version="1.0" encoding="utf-8"?>\n{HEADER}\n{VECTOR_OPEN.format(extra=extra)}{body}</vector>\n'


def android_color(hex_color):
    return "#FF" + hex_color.lstrip("#").upper()


def foreground_xml(layers):
    return vector("".join(
        f'    <path android:fillColor="{color}" android:fillAlpha="{alpha}" android:pathData="{circle_path(circles)}" />\n'
        for color, alpha, circles in layers
    ))


def monochrome_xml(layers):
    # Themed icons take one colour from the system, so only alpha carries the shading. The halo
    # exists to separate the notch from the dots in colour; in one colour it would be a blot.
    return vector("".join(
        f'    <path android:fillColor="#FFFFFF" android:fillAlpha="{alpha}" android:pathData="{circle_path(circles)}" />\n'
        for color, alpha, circles in layers if color != HALO
    ))


def background_xml():
    gx, gy = GLOW_CENTER
    body = (
        f'    <path android:pathData="M0,0h{GRID}v{GRID}h-{GRID}z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        f'            <gradient android:type="radial" android:centerX="{fmt(gx * GRID)}" '
        f'android:centerY="{fmt(gy * GRID)}" android:gradientRadius="{fmt(GLOW_RADIUS * GRID)}">\n'
        f'                <item android:offset="0" android:color="{android_color(GLOW_INNER)}" />\n'
        f'                <item android:offset="1" android:color="{android_color(GLOW_OUTER)}" />\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>\n'
    )
    return vector(body, extra='\n    xmlns:aapt="http://schemas.android.com/aapt"')


def favicon_svg(layers):
    # The favicon shows what a launcher shows: the middle 72 units, in a rounded square.
    gx, gy = GLOW_CENTER
    view = (GRID - 72) / 2
    shapes = "".join(
        f'<path fill="{color}" fill-opacity="{alpha}" d="{circle_path(circles)}"/>\n'
        for color, alpha, circles in layers
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{fmt(view)} {fmt(view)} 72 72">\n'
        f'<defs><radialGradient id="glow" gradientUnits="userSpaceOnUse" cx="{fmt(gx * GRID)}" cy="{fmt(gy * GRID)}" '
        f'r="{fmt(GLOW_RADIUS * GRID)}"><stop offset="0" stop-color="{GLOW_INNER}"/>'
        f'<stop offset="1" stop-color="{GLOW_OUTER}"/></radialGradient></defs>\n'
        f'<rect x="{fmt(view)}" y="{fmt(view)}" width="72" height="72" rx="16" fill="url(#glow)"/>\n'
        f'{shapes}</svg>\n'
    )


def main():
    layers = dial_layers()
    outputs = {
        DRAWABLE / "ic_launcher_background.xml": background_xml(),
        DRAWABLE / "ic_launcher_foreground.xml": foreground_xml(layers),
        DRAWABLE / "ic_launcher_monochrome.xml": monochrome_xml(layers),
        FAVICON: favicon_svg(layers),
    }
    for path, text in outputs.items():
        path.write_text(text)
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
